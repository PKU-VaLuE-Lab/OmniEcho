#!/usr/bin/env python3


#   python 08_align_stop_prompt_and_merge.py
"""OmniEcho processing component."""
from __future__ import annotations

import argparse
import json
import os
from settings import DATA_ROOT as TRAJECTORY_ROOT, NAV_ROOT as OUTPUT_ROOT, MODEL_ROOT, API_BASE_URL as SERVICE_URL, API_MODEL
import sys

BASE = os.path.join(OUTPUT_ROOT, "spatial_voice_vln_omni_sft_cot.jsonl")
STOP = os.path.join(OUTPUT_ROOT, "vln_stop_within1m_cot.jsonl")


CLAUSE = ("each waypoint formatted as [x, y, yaw] where x is forward in meters, "
          "y is left in meters, and yaw is the heading in radians.")

CLAUSE_NEW = (CLAUSE[:-1] + ", or the single token <stop>. Once you have reached the sound source "
              "(within about 1 meter), output <stop> for every remaining waypoint; if you are "
              "already at the source, output <stop> for all of them.")


def align_content(content):
    """OmniEcho processing component."""
    if isinstance(content, str):
        if CLAUSE in content:
            return content.replace(CLAUSE, CLAUSE_NEW), content.count(CLAUSE)
        return content, 0
    if isinstance(content, list):
        n = 0
        new = []
        for part in content:
            if isinstance(part, dict) and part.get("type") == "text" and isinstance(part.get("text"), str) \
                    and CLAUSE in part["text"]:
                part = dict(part)
                c = part["text"].count(CLAUSE)
                part["text"] = part["text"].replace(CLAUSE, CLAUSE_NEW)
                n += c
            new.append(part)
        return new, n
    return content, 0


def prompt_has_stop(rec):
    """OmniEcho processing component."""
    try:
        c = rec["messages"][0]["content"]
    except Exception:
        return False
    if isinstance(c, str):
        return "<stop>" in c
    if isinstance(c, list):
        return any(isinstance(p, dict) and p.get("type") == "text"
                   and isinstance(p.get("text"), str) and "<stop>" in p["text"] for p in c)
    return False


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", default=BASE, help="Main training file to align and overwrite (stoptoken)")
    ap.add_argument("--stop", default=STOP, help="Stop-sample JSONL generated by stage 7, appended to the output")
    ap.add_argument("--out", default=None, help="Output path (default: overwrite base in place)")
    ap.add_argument("--no-merge", action="store_true", help="Align prompts without appending stop samples")
    ap.add_argument("--dry-run", action="store_true", help="Report counts without writing files")
    ap.add_argument("--force", action="store_true", help="Continue even if the input appears aligned or merged already")
    args = ap.parse_args()

    out_path = args.out or args.base
    if not os.path.exists(args.base):
        print(f"[fatal] Base file does not exist: {args.base}", file=sys.stderr); sys.exit(1)


    pre_stop = 0
    total = 0
    with open(args.base) as f:
        for ln in f:
            ln = ln.strip()
            if not ln:
                continue
            total += 1
            try:
                if prompt_has_stop(json.loads(ln)):
                    pre_stop += 1
            except json.JSONDecodeError:
                continue
    if pre_stop > 0 and not args.force:
        print(f"[abort] {pre_stop}/{total} base prompts already contain <stop>; this script may have run already.\n"
              f"        To rerun, add --force. Merging appends stop samples again and may create duplicates.", file=sys.stderr)
        sys.exit(2)
    print(f"[info] Base records: {total} (preflight: {pre_stop} prompts already contain <stop>)")


    stop_lines = []
    if not args.no_merge:
        if not os.path.exists(args.stop):
            print(f"[fatal] Stop-sample file does not exist: {args.stop}\n"
                  f"        Generate it with 07_make_stop_vln_cot_dataset.py first, or use --no-merge to align only.",
                  file=sys.stderr)
            sys.exit(1)
        bad = 0
        with open(args.stop) as f:
            for ln in f:
                ln = ln.strip()
                if not ln:
                    continue
                try:
                    rec = json.loads(ln)
                except json.JSONDecodeError:
                    bad += 1
                    continue
                if not prompt_has_stop(rec):
                    bad += 1   
                stop_lines.append(ln)
        print(f"[info] Stop samples: {len(stop_lines)} (missing <stop> in prompt or invalid rows: {bad})")
        if bad and not args.force:
            print(f"[abort] Found {bad} invalid stop samples; --force is required to continue.", file=sys.stderr)
            sys.exit(2)


    changed = 0          
    replaced = 0         
    n_out = 0
    if args.dry_run:
        with open(args.base) as f:
            for ln in f:
                ln = ln.strip()
                if not ln:
                    continue
                try:
                    rec = json.loads(ln)
                except json.JSONDecodeError:
                    continue
                _, k = align_content(rec["messages"][0]["content"])
                if k:
                    changed += 1
                    replaced += k
                n_out += 1
        print(f"[dry-run] Would update {changed} navigation prompts ({replaced} CLAUSE replacements); "
              f"leave {n_out - changed} records unchanged (e.g. QA-only samples)")
        if not args.no_merge:
            print(f"[dry-run] Would append {len(stop_lines)} stop samples; merged total: {n_out + len(stop_lines)}")
        print("[dry-run] No files written.")
        return

    tmp_path = out_path + ".tmp"
    with open(tmp_path, "w") as fo:
        with open(args.base) as f:
            for ln in f:
                s = ln.strip()
                if not s:
                    continue
                try:
                    rec = json.loads(s)
                except json.JSONDecodeError:
                    fo.write(ln if ln.endswith("\n") else ln + "\n")  
                    n_out += 1
                    continue
                new_content, k = align_content(rec["messages"][0]["content"])
                if k:
                    rec["messages"][0]["content"] = new_content
                    changed += 1
                    replaced += k
                fo.write(json.dumps(rec, ensure_ascii=False) + "\n")
                n_out += 1
        n_base_out = n_out
        
        for ln in stop_lines:
            fo.write(ln + "\n")
            n_out += 1

    print(f"[info] Aligned: updated {changed} navigation prompts ({replaced} replacements), wrote {n_base_out} base records")
    if not args.no_merge:
        print(f"[info] Merged: appended {len(stop_lines)} stop samples")
    print(f"[info] Temporary file total: {n_out} records -> {tmp_path}")


    expect = n_base_out + (0 if args.no_merge else len(stop_lines))
    if n_out != expect:
        print(f"[fatal] Row-count mismatch: actual {n_out} != expected {expect}; preserving the temporary file without overwriting.", file=sys.stderr)
        sys.exit(3)
    os.replace(tmp_path, out_path)
    print(f"[done] {'Overwrote' if out_path == args.base else 'Wrote'} -> {out_path}  ({n_out} records)")


if __name__ == "__main__":
    main()
